//Вказівник в мові С - це змінна, значенням якої є адреса комірки в оперативній пам'яті, де зберігається другі дані
//Вказівник при оголошенні змінноє має "*" перед самой змінною, наприклад int *var1;
//Також для того щоб повернути адресу змінної в пам'яті використовується оператор поверненняя адреси "&" наприклад var = &a
//щоб отримати доступ до вказівника перед змінною використовується "*", наприклад *var1 = 5 - це називається розіменуванням вказівника

//Виділення пам’яті в мові C — це процес резервування ділянок оперативної пам’яті для зберігання змінних, масивів і структур під час виконання програми
//серед типів виділення пам'яті є статичне виділення пам'яті(пам’ять виділяється на етапі початку виконання та існує протягом усього часу роботи програми) і динамічне виділення пам'яті(пам’ять запитується вручну під час виконання програми і звільняється через free)

//Цикл роботи з динамічною пам’яттю в мові C — це сувора послідовність етапів від виділення блоку пам’яті за допомогою вказівників до його обов’язкового звільнення.
//Варіанти функій для роботи з динамічною пам'яттю:
//функія malloc - Виділення пам’яті. Пам’ять не очищується під час виконання і містить "сміття"
//функція calloc - Виділення пам'яті та обнулення. Усі виділені байти автоматично заповнюються нулями
//функція realloc - Збільшує або зменшує раніше виділений блок пам’яті. Старі дані зберігаються.
// функція free - Звільнення пам’яті.

#include <stdio.h>
#include <stdlib.h>

int main() {
    int n, m;

    // 1. Отримуємо розміри матриці від користувача
    printf("Enter rows (n) and coluums (m) of matrix: ");
    scanf("%d %d", &n, &m);

    // 2. Виділяємо пам'ять під масив вказівників (рядки матриці)
    double **matrix = (double **)malloc(n * sizeof(double *));
    if (matrix == NULL) {
        printf("Error for highlighting of memory.\n");
        return 1;
    }

    // 3. Виділяємо пам'ять під кожен окремий рядок (елементи типу double)
    for (int i = 0; i < n; i++) {
        matrix[i] = (double *)malloc(m * sizeof(double));
        
        // Якщо пам'ять не виділилася на якомусь кроці, звільняємо все, що встигли виділити раніше
        if (matrix[i] == NULL) {
            printf("Error for highlighting memory for row %d.\n", i);
            for (int j = 0; j < i; j++) {
                free(matrix[j]);
            }
            free(matrix);
            return 1;
        }
    }

    // 4. Заповнення та виведення матриці для перевірки
    printf("\nMatrix:\n");
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < m; j++) {
            matrix[i][j] = (i + 1) + (j + 1) * 0.1; // Приклад заповнення
            printf("%.1f ", matrix[i][j]);
        }
        printf("\n");
    }

    // 5. КОРЕКТНЕ ЗНИЩЕННЯ МАТРИЦІ
    // Спочатку звільняємо пам'ять кожного рядка
    for (int i = 0; i < n; i++) {
        free(matrix[i]);
    }
    // Потім звільняємо пам'ять самого масиву вказівників
    free(matrix);
    // Обнуляємо вказівник для уникнення звернення до звільненої пам'яті (dangling pointer)
    matrix = NULL;

    printf("\nMemoey is free.\n");
    return 0;
}